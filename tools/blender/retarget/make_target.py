# Writes a retarget target profile for one of Emberfall's rig.py fighters, read from the rig spec that its build script
# writes (assets/<fighter>/work/rig.json). The profile names which bones the pipeline drives and how:
#   body turns:   hips, spine, chest, head                       ("qb" turns, rig.py's own form)
#   reach:        hand and foot IK controls (c_hand*, c_foot*)    ("move")
#   wrists/feet:  hand and foot bones                             ("qb" on top of whatever the IK does)
#   held props:   the copy-rotation controls (c_sword, c_shield)  ("qb", following the hand that holds them)
# Run with any Python 3 (Blender's included):
#   blender -b --factory-startup --python tools/blender/retarget/make_target.py -- --spec assets/brand/work/rig.json --name brand --manifest Brand --out tools/blender/retarget/targets/brand.json
import sys, json, os

args = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
opt = {args[i].lstrip('-'): args[i + 1] for i in range(0, len(args), 2)}
spec = json.load(open(opt['spec'], encoding='utf-8'))
bones = {b['name']: b for b in spec['bones']}
kids = {n: [c for c, b in bones.items() if b.get('parent') == n] for n in bones}
side = lambda n: n[-1] if n[-1] in 'LR' else None
deform = lambda n: bones[n].get('deform', True)

roles, ik = {}, {}
for e in spec.get('ik', []):
    ctl, lower = e['name'], e['bone']; upper = bones[lower]['parent']; s = side(ctl)
    end = [c for c in kids[lower] if deform(c)]
    if not end or not s: raise SystemExit('make_target: cannot read IK chain ' + ctl)
    leg = 'foot' in ctl.lower() or bones[lower]['head'][1] < bones[upper]['head'][1] * 0.75 and bones[upper]['head'][1] < 1.2
    kind = ('thigh', 'shin', 'foot') if leg else ('upperArm', 'foreArm', 'hand')
    roles[kind[0] + '.' + s], roles[kind[1] + '.' + s], roles[kind[2] + '.' + s] = upper, lower, end[0]
    ik[kind[2] + '.' + s] = ctl
need = [r + '.' + s for r in ('upperArm', 'foreArm', 'hand', 'thigh', 'shin', 'foot') for s in 'LR']
missing = [r for r in need if r not in roles]
if missing: raise SystemExit('make_target: no IK chain for ' + ', '.join(missing))
hips = bones[roles['thigh.L']]['parent']; chest = bones[roles['upperArm.L']]['parent']
chain = [chest]
while chain[-1] != hips and bones[chain[-1]].get('parent'): chain.append(bones[chain[-1]]['parent'])
if chain[-1] != hips: raise SystemExit('make_target: the arms do not hang off a chain from the hips')
chain = chain[::-1]   # hips ... chest
roles['hips'] = hips; roles['chest'] = chest; roles['spine'] = chain[1] if len(chain) > 2 else chest
heads = [c for c in kids[chest] if deform(c) and c not in (roles['upperArm.L'], roles['upperArm.R'])]
if not heads: raise SystemExit('make_target: no head on the chest')
roles['head'] = max(heads, key=lambda c: bones[c]['head'][1])

props = []
for cr in spec.get('copyrot', []):
    b = cr['bone']; p = b; s = None
    while p:
        if p == roles['hand.L']: s = 'L'
        if p == roles['hand.R']: s = 'R'
        p = bones[p].get('parent')
    if not s: continue
    tip = next((c for c in kids[b] if deform(c)), None)
    props.append({'control': cr['from'], 'bone': b, 'tip': tip, 'side': s})

base = opt.get('base', 'stand') if opt.get('base', 'stand') in spec.get('poses', {}) else None
neutral = {}
if base:
    for r in ('hips', 'spine', 'chest', 'head'):
        e = spec['poses'][base].get(roles[r], {})
        if e.get('rot'): neutral[roles[r]] = e['rot']
ys = [b[k][1] for b in spec['bones'] for k in ('head', 'tail') if b.get('deform', True)]
game_h = None
if opt.get('manifest'):
    mf = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'assets', 'manifest.json')
    try: game_h = json.load(open(mf, encoding='utf-8'))[opt['manifest']]['height']
    except Exception as e: print('make_target: no manifest height (%s)' % e)
rel = lambda p: os.path.relpath(os.path.abspath(p), os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')).replace('\\', '/')
prof = {
    'name': opt.get('name', 'target'),
    'spec': rel(opt['spec']),
    'glb': opt.get('glb'),
    'manifest': opt.get('manifest'),
    'gameHeight': game_h,
    'modelHeight': round(max(ys), 4),
    'basePose': base,
    'roles': roles,
    'ik': ik,
    'ikParent': {c: bones[c].get('parent') for c in ik.values()},
    'props': props,
    'neutral': neutral,
    'note': 'Generated by make_target.py from %s; check the roles before use. "neutral" turns (rig.py rot) are kept under the capture (the face the mesh was modelled with).' % rel(opt['spec']),
}
os.makedirs(os.path.dirname(os.path.abspath(opt['out'])), exist_ok=True)
json.dump(prof, open(opt['out'], 'w', encoding='utf-8'), indent=1)
print('make_target: %s: %s' % (opt['out'], ', '.join('%s=%s' % kv for kv in sorted(roles.items()))))
print('make_target: IK %s; props %s; neutral %s' % (ik, [(p['control'], p['bone'], p['side']) for p in props], neutral))
